class AIService:
    def __init__(self):
        # We initialize multiple clients for rotation
        self.keys = config.groq_keys
        self.clients = [
            AsyncOpenAI(api_key=k, base_url="https://api.groq.com/openai/v1")
            for k in self.keys
        ]
        
        # Primary models that are currently stable on Groq
        self.models_to_try = [
            "llama-3.3-70b-versatile",
            "llama-3.1-405b-reasoning", # Best quality
            "llama-3.1-70b-versatile",  # Fallback if up
            "llama-3.1-8b-instant",     # Fast fallback
            "gemma2-9b-it"              # Reliable small model
        ]
        
        logging.info(f"AI Service (Liya) initialized with {len(self.keys)} API keys.")

    async def get_answer(self, question: str, language: str = "ru") -> str:
        # Determine current language string for system message reinforcing
        lang_str = "Русский (Russian)" if language == "ru" else "Հայերեն (Armenian)"
        
        # Format prompt with current manager ID from Render environment
        formatted_prompt = SYSTEM_PROMPT.replace("{manager_id}", str(config.manager_id))
        
        # Rotation through API KEYS
        for i, client in enumerate(self.clients):
            # Try MODELS for each key until success
            for model in self.models_to_try:
                try:
                    logging.info(f"Trying Liya (Key {i+1}/{len(self.keys)}) with {model} in {lang_str}...")
                    response = await client.chat.completions.create(
                        model=model,
                        messages=[
                            {"role": "system", "content": formatted_prompt + f"\n\nТЕКУЩИЙ ЯЗЫК ОБЩЕНИЯ: {lang_str}"},
                            {"role": "user", "content": question}
                        ],
                        temperature=0.5,
                        max_tokens=1500
                    )
                    
                    if response and response.choices:
                        return response.choices[0].message.content
                        
                except Exception as e:
                    msg = str(e).lower()
                    # 429 = Rate Limit, 413 = Payload Too Large (TPM limit on small models)
                    if "429" in msg or "413" in msg:
                        logging.warning(f"Key {i+1} or Model {model} hit quota/limit. Moving to next provider seat.")
                        break # Exit model loop to try the NEXT KEY with the primary model
                    elif "400" in msg and "decommissioned" in msg:
                        logging.warning(f"Model {model} is decommissioned. Skipping to next valid model.")
                        continue # Try next model with the same key
                    else:
                        logging.error(f"Unexpected error on Key {i+1}, Model {model}: {e}")
                        continue
                        
        return "Извините, я временно исчерпала лимиты всех доступных токенов на сегодня. Пожалуйста, обратитесь к менеджеру напрямую через кнопку ниже. 👱‍♀️"

ai_service = AIService()
